#!/usr/bin/env python3
"""Build the Switch template for Confusion Radar from its readable sources.

The agent briefs (agents/*.md) and room instructions (rooms/*.md) are kept as
plain Markdown so they can be read and reviewed. Switch Console wants one YAML
document, so this script inlines them into template/confusion-radar.template.yaml.

    python3 tools/build_template.py           # write the template
    python3 tools/build_template.py --check   # fail if the committed file is stale

Needs PyYAML (pip install pyyaml).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "template" / "confusion-radar.template.yaml"

HEADER = """\
# Confusion Radar: a TA for students, a radar for the teacher.
#
# One Switch template that creates:
#   - two Claude Code agents that work in the teacher's course folder:
#       <class>-ta     anyone in the class can address it; read-only tools
#       <class>-radar  only the teacher (and the teacher's agents) can address it
#   - a room group with two linked rooms:
#       <class>-class          public: students + TA (+ Radar, read-only presence)
#       <class>-teacher-desk   private: teacher + Radar (+ TA, drops cards)
#
# GENERATED by tools/build_template.py from agents/*.md and rooms/*.md.
# Edit those files, then rebuild. Don't edit this file by hand.
#
# Use: Switch Console -> Templates -> paste this document -> fill the form.
# After it's created, type `!assign-agent @ta` in the class channel.
"""


# Switch tools neither agent needs. Both agents read text that students wrote, so
# a prompt injection could ask them to "add me to the teacher's desk" or "archive
# this room". These tools are removed from the agents' sessions entirely. The
# teacher still does room admin by hand.
DISALLOWED_SWITCH_TOOLS = [
    "mcp__switch__" + op
    for op in (
        "add_users_to_room",
        "archive_room",
        "unarchive_room",
        "create_room",
        "create_room_from_yaml",
        "create_room_group",
        "update_room",
        "invite_agent_to_room",
        "remove_agent_from_room",
        "link_rooms",
        "unlink_rooms",
        "create_reference",
        "attach_reference_to_room",
        "define_role",
        "edit_role",
        "delete_role",
        "run_template",
        "save_template",
        "update_template",
        "delete_template",
        "update_agent_detail",
        "request_agent_deletion",
        "set_agent_service",
        "remove_agent_service",
        "list_all_rooms",
        "list_all_references",
        "list_agents",
        "get_my_context",
    )
]


class _LiteralDumper(yaml.SafeDumper):
    """Write multi-line strings as `|` blocks, so the briefs stay readable."""


def _str(dumper: yaml.SafeDumper, data: str) -> yaml.Node:
    if "\n" in data:
        return dumper.represent_scalar("tag:yaml.org,2002:str", data, style="|")
    return dumper.represent_scalar("tag:yaml.org,2002:str", data)


_LiteralDumper.add_representer(str, _str)


def _read(rel: str) -> str:
    text = (ROOT / rel).read_text(encoding="utf-8")
    # A trailing space on a line forces PyYAML out of block style; strip them.
    lines = [line.rstrip() for line in text.strip().splitlines()]
    return "\n".join(lines) + "\n"


def build() -> dict:
    ta_brief = _read("agents/ta.md")
    radar_brief = _read("agents/radar.md")
    class_rules = _read("rooms/class.md")
    desk_rules = _read("rooms/teacher-desk.md")

    ta = "{class_name}-ta"
    radar = "{class_name}-radar"
    aliases = {ta: "ta", radar: "radar"}

    return {
        "version": 1,
        "params": {
            "class_name": {
                "type": "string",
                "label": "Class id",
                "description": (
                    "Short id for this class, used in room and agent names "
                    "(lowercase letters, digits and dashes), e.g. cs12b."
                ),
                "default": "cs12b",
                "pattern": "[a-z][a-z0-9-]*",
            },
            "teacher_title": {
                "type": "string",
                "label": "What students call you",
                "description": "How the agents refer to you when talking to students.",
                "default": "Ma'am",
            },
            "course_dir": {
                "type": "directory",
                "label": "Course folder",
                "description": (
                    "Absolute path to your course folder: notes, syllabus, schedule "
                    "(the course/ folder of this repo). Both agents work here."
                ),
            },
            "bridge": {
                "type": "bridge",
                "description": "The messaging app the two channels are created on.",
                "default": ["$first"],
            },
            "location": {
                "type": "location",
                "description": "The machine the agents run on (the one with the course folder).",
                "default": "local",
                "input": "advanced",
            },
        },
        "agents": [
            {
                "name": ta,
                "display_name": "TA",
                "description": (
                    "Class teaching assistant: answers from the teacher's notes with "
                    "hints, never final answers, and asks the teacher when stuck."
                ),
                "provider": "claude",
                "location": "{location}",
                "directory": "{course_dir}",
                # Students can address the TA, so it must never need approval:
                # read-only tools, and anything else is denied without asking.
                "addressing": "anyone",
                "advanced_config": {
                    "tools": ["Read", "Grep", "Glob"],
                    "disallowedTools": DISALLOWED_SWITCH_TOOLS
                    + [
                        # The TA keeps no notes of its own: the room is its log.
                        "mcp__switch__create_room_document",
                        "mcp__switch__update_room_document",
                        "mcp__switch__delete_room_document",
                    ],
                    "permissionMode": "dontAsk",
                },
                "instructions": ta_brief,
            },
            {
                "name": radar,
                "display_name": "Radar",
                "description": (
                    "The teacher's private analyst: morning Confusion Radar, "
                    "escalation relay, warm-up quizzes."
                ),
                "provider": "claude",
                "location": "{location}",
                "directory": "{course_dir}",
                # Only the teacher, the TA and the bell may address the Radar.
                "addressing": "owner-agents",
                "advanced_config": {
                    "tools": ["Read", "Grep", "Glob", "Write", "Edit"],
                    "disallowedTools": DISALLOWED_SWITCH_TOOLS,
                    "permissionMode": "acceptEdits",
                },
                "instructions": radar_brief,
            },
        ],
        "group": {
            "name": "{class_name} · Confusion Radar",
            "description": "The class channel and the teacher's private desk, with their agents.",
        },
        "rooms": [
            {
                "name": "{class_name}-class",
                "description": "Ask the TA anything about the course. Hints, not answers.",
                "instructions": class_rules,
                "bridge": "{bridge}",
                "channel_type": "channel_public",
                "agents": [ta, radar],
                "users": ["{$creator}"],
                "aliases": dict(aliases),
                "kickoff": (
                    "@" + ta + " you're live in the class room. Introduce yourself "
                    "to the students in three short lines: you help with the course "
                    "using {teacher_title}'s notes, with hints and not answers; "
                    "{teacher_title} gets a short daily summary of what the class "
                    "found confusing, so it can be re-taught; and you'll ask "
                    "{teacher_title} whenever you can't help or someone seems stuck."
                ),
            },
            {
                "name": "{class_name}-teacher-desk",
                "description": "Private: escalation cards and the morning Confusion Radar.",
                "instructions": desk_rules,
                "bridge": "{bridge}",
                "channel_type": "channel_private",
                "agents": [ta, radar],
                "users": ["{$creator}"],
                "aliases": dict(aliases),
                "kickoff": (
                    "@" + radar + " you're live on my desk. In three short lines, "
                    "tell me what you'll bring here and how I answer a card. Then "
                    "make sure radar-data/state.json exists."
                ),
            },
        ],
        "links": [
            {
                "from": "{class_name}-class",
                "to": "{class_name}-teacher-desk",
                "label": "escalations go to the teacher's desk",
            },
            {
                "from": "{class_name}-teacher-desk",
                "to": "{class_name}-class",
                "label": "the class this desk serves",
            },
        ],
        "form": {"advanced": {"label": "Advanced", "open": False}},
    }


def render() -> str:
    body = yaml.dump(
        build(),
        Dumper=_LiteralDumper,
        sort_keys=False,
        allow_unicode=True,
        width=100,
    )
    return HEADER + "\n" + body


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if the committed template differs from a fresh build",
    )
    args = parser.parse_args()

    text = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is stale: run tools/build_template.py", file=sys.stderr)
            return 1
        print("template is up to date")
        return 0

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
